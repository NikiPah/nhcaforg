/* eslint-disable @typescript-eslint/no-require-imports -- Standalone CommonJS browser runner. */
const assert = require("node:assert/strict");
const { chromium } = require("playwright");

async function main() {
  const origin = process.env.PORTAL_TEST_ORIGIN || "http://127.0.0.1:3001";
  const csrf = await fetch(`${origin}/api/assistance-inquiries`, { method: "POST", headers: { Origin: "https://unrelated.example", "Content-Type": "application/json" }, body: "{}" });
  assert.equal(csrf.status, 403);
  const invalid = await fetch(`${origin}/api/assistance-inquiries`, { method: "POST", headers: { Origin: origin, "Content-Type": "application/json" }, body: JSON.stringify({ inquiry_id: crypto.randomUUID(), website: "" }) });
  assert.equal(invalid.status, 400);
  assert.match(invalid.headers.get("cache-control"), /no-store/);
  assert.equal((await fetch(`${origin}/api/assistance-inquiries`)).status, 405);
  assert.equal((await fetch(`${origin}/api/portal`)).status, 410);
  for (const path of ["/portal", "/portal/demo", "/portal/auth/callback"]) assert.equal(new URL((await fetch(origin + path)).url).pathname, "/apply");
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", args: ["--no-sandbox"] });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
    const page = await context.newPage();
    page.setDefaultTimeout(15000);
    const errors = [];
    context.on("page", (page) => page.on("pageerror", (error) => errors.push(error.message)));
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(origin);
    assert.equal(await page.locator('a[href="#apply"]').count(), 0);
    const headerApply = page.getByRole("banner").getByRole("link", { name: /^Apply for Assistance/ });
    assert.equal(await headerApply.getAttribute("href"), "/apply");
    assert.equal(await headerApply.getAttribute("target"), "_blank");
    const [formPage] = await Promise.all([page.waitForEvent("popup"), headerApply.click()]);
    formPage.setDefaultTimeout(15000);
    await formPage.getByRole("heading", { name: "Welcome to NHCAF’s online assistance application", exact: true }).waitFor();
    assert.equal(new URL(page.url()).pathname, "/");
    assert.equal(await formPage.evaluate(() => window.opener), null);
    assert.equal(await formPage.getByRole("button", { name: /sign in|log in/i }).count(), 0);
    assert.equal(await formPage.locator('input[type="file"]').count(), 0);
    const progress = formPage.getByRole("progressbar", { name: "Application progress" });
    assert.equal(await progress.getAttribute("value"), "0");
    const nav = formPage.getByRole("navigation", { name: "Application steps", exact: true });
    assert.equal(await nav.getByRole("button").count(), 7);
    assert.equal(await nav.getByRole("button", { name: "Final Review", exact: true }).isDisabled(), true);
    assert.equal(await formPage.getByRole("button", { name: "Submit inquiry", exact: true }).isDisabled(), true);
    await formPage.screenshot({ path: "/tmp/nhcaf-apply-preview.png", fullPage: true });
    await formPage.getByRole("radio", { name: "Español", exact: true }).check();
    await formPage.getByRole("heading", { name: "Bienvenido/a a la solicitud de ayuda de NHCAF", exact: true }).waitFor();
    assert.equal(await formPage.locator(".assistance-page").getAttribute("lang"), "es");
    await formPage.screenshot({ path: "/tmp/nhcaf-apply-welcome-spanish.png", fullPage: true });
    await formPage.getByRole("radio", { name: "English", exact: true }).check();
    const sent = [];
    let rejectFirst = true;
    await formPage.route("**/api/assistance-inquiries", async (route) => {
      const payload = route.request().postDataJSON(); sent.push(payload);
      if (rejectFirst) { rejectFirst = false; return route.fulfill({ status: 503, json: { error: "Test service unavailable. Please try again." } }); }
      await route.fulfill({ status: 201, json: { reference: `NHCAF-${payload.inquiry_id.replaceAll("-", "").toUpperCase()}` } });
    });
    const next = () => formPage.getByRole("button", { name: "Next", exact: true }).click();
    await next();
    assert.equal(await progress.getAttribute("value"), "14");
    await next();
    await formPage.getByRole("heading", { name: "Let’s get started.", exact: true }).waitFor();
    await formPage.getByRole("checkbox", { name: "I am the patient, or I am authorized", exact: false }).check();
    await next();
    await formPage.getByRole("combobox", { name: "Has the patient received a cancer diagnosis?", exact: false }).selectOption("Yes");
    await formPage.getByLabel("Number of people in the household", { exact: false }).fill("2");
    await formPage.getByRole("checkbox", { name: "I need help estimating household income.", exact: true }).check();
    assert.equal(await formPage.locator('input[name="income_amount"]').count(), 0);
    await formPage.getByRole("checkbox", { name: "I need help estimating household income.", exact: true }).uncheck();
    await formPage.getByLabel("Household income before taxes", { exact: false }).fill("0");
    await formPage.getByRole("radio", { name: "Español", exact: true }).check();
    assert.equal(await formPage.getByLabel("Número de personas en el hogar", { exact: false }).inputValue(), "2");
    assert.equal(await formPage.getByLabel("Ingresos del hogar antes de impuestos", { exact: false }).inputValue(), "0");
    await formPage.getByRole("radio", { name: "English", exact: true }).check();
    await next();
    await next();
    await formPage.getByRole("alert").filter({ hasText: "Choose at least one" }).waitFor();
    await formPage.getByRole("checkbox", { name: "Food assistance", exact: true }).check();
    await formPage.getByRole("button", { name: "Previous", exact: true }).click();
    assert.equal(await formPage.getByLabel("Household income before taxes", { exact: false }).inputValue(), "0");
    await next();
    assert.equal(await formPage.getByRole("checkbox", { name: "Food assistance", exact: true }).isChecked(), true);
    await formPage.screenshot({ path: "/tmp/nhcaf-apply-assistance-step.png", fullPage: true });
    await next();
    await formPage.getByRole("combobox", { name: "Can you provide proof of income?", exact: false }).selectOption("I need help obtaining this");
    await formPage.getByRole("combobox", { name: "Can you provide proof of cancer diagnosis?", exact: false }).selectOption("I can provide this");
    await next();
    await formPage.getByLabel("Your name", { exact: false }).fill("Alex Example");
    await formPage.getByLabel("Phone number", { exact: false }).fill("555-010-2345");
    await formPage.getByLabel("County", { exact: false }).fill("Harris");
    await formPage.getByLabel("ZIP code", { exact: false }).fill("77373");
    await next();
    assert.equal(sent.length, 0, "Moving through steps must not send applicant data");
    assert.equal(await formPage.getByRole("button", { name: "Submit inquiry", exact: true }).isDisabled(), true);
    await formPage.getByRole("button", { name: "Edit: Patient Information", exact: true }).click();
    await formPage.getByLabel("Your name", { exact: false }).fill("Alex Revised");
    await next();
    assert.match(await formPage.locator(".assistance-review-group").last().innerText(), /Alex Revised/);
    await formPage.getByRole("checkbox", { name: /I confirm that this information is accurate/ }).check();
    for (const width of [1440, 1024, 390, 320]) {
      await formPage.setViewportSize({ width, height: 1000 });
      assert.equal(await formPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Wizard fits ${width}px`);
      const contentBox = await formPage.locator(".assistance-wizard-content").boundingBox();
      assert.ok(contentBox.x >= 0 && contentBox.x + contentBox.width <= width, `Wizard content is not clipped at ${width}px`);
    }
    await formPage.setViewportSize({ width: 1440, height: 1100 });
    await formPage.screenshot({ path: "/tmp/nhcaf-apply-final-review.png", fullPage: true });
    await formPage.getByRole("button", { name: "Submit inquiry", exact: true }).click();
    await formPage.getByRole("alert").filter({ hasText: "Test service unavailable" }).waitFor();
    assert.equal(await formPage.getByRole("heading", { name: "We received your assistance inquiry." }).count(), 0);
    assert.match(await formPage.locator(".assistance-review-group").last().innerText(), /Alex Revised/);
    await formPage.getByRole("button", { name: "Submit inquiry", exact: true }).click();
    await formPage.getByRole("heading", { name: "We received your assistance inquiry." }).waitFor();
    assert.equal(sent.length, 2);
    assert.equal(sent[0].inquiry_id, sent[1].inquiry_id);
    assert.equal(sent[1].income_amount, 0);
    assert.equal(sent[1].patient_name, "Alex Revised");
    assert.equal(sent[1].diagnosis_status, "Yes");
    assert.equal(await progress.getAttribute("value"), "100");
    assert.equal(await formPage.evaluate(() => document.activeElement.id), "receipt-heading");
    assert.deepEqual(await formPage.evaluate(() => Object.keys(localStorage)), []);
    assert.deepEqual(await formPage.context().cookies(), []);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("button", { name: "Open menu", exact: true }).click();
    const [mobile] = await Promise.all([page.waitForEvent("popup"), page.getByRole("navigation", { name: "Primary mobile", exact: true }).getByRole("link", { name: /^Apply for Assistance/ }).click()]);
    await mobile.getByRole("heading", { name: "Welcome to NHCAF’s online assistance application", exact: true }).waitFor();
    mobile.setDefaultTimeout(15000);
    await mobile.setViewportSize({ width: 390, height: 844 });
    await mobile.getByRole("button", { name: "Next", exact: true }).click();
    await mobile.getByRole("radio", { name: "Family member or caregiver", exact: true }).check();
    await mobile.getByRole("checkbox", { name: "I am the patient, or I am authorized", exact: false }).check();
    await mobile.getByRole("button", { name: "Next", exact: true }).click();
    await mobile.getByLabel("Number of people in the household", { exact: false }).fill("3");
    mobile.once("dialog", (dialog) => dialog.accept());
    await mobile.getByRole("button", { name: "Cancel", exact: true }).click();
    await mobile.getByRole("heading", { name: "Welcome to NHCAF’s online assistance application", exact: true }).waitFor();
    assert.equal(await mobile.getByRole("progressbar").getAttribute("value"), "0");
    await mobile.getByRole("radio", { name: "Español", exact: true }).check();
    await mobile.getByRole("button", { name: "Siguiente", exact: true }).click();
    assert.equal(await mobile.getByRole("radio", { name: "Paciente", exact: true }).isChecked(), true);
    assert.equal(await mobile.getByRole("checkbox").isChecked(), false);
    await mobile.getByRole("radio", { name: "Familiar o persona cuidadora", exact: true }).check();
    await mobile.getByRole("checkbox").check();
    await mobile.getByRole("button", { name: "Siguiente", exact: true }).click();
    await mobile.getByRole("combobox", { name: "¿El paciente ha recibido un diagnóstico de cáncer?", exact: false }).selectOption("Not yet confirmed");
    await mobile.getByLabel("Número de personas en el hogar", { exact: false }).fill("2");
    await mobile.getByRole("checkbox", { name: "Necesito ayuda para estimar los ingresos del hogar.", exact: true }).check();
    await mobile.getByRole("button", { name: "Siguiente", exact: true }).click();
    await mobile.getByRole("checkbox", { name: "Transporte relacionado con el tratamiento", exact: true }).check();
    await mobile.getByRole("button", { name: "Siguiente", exact: true }).click();
    await mobile.getByRole("combobox", { name: "¿Puede presentar un comprobante de ingresos?", exact: false }).selectOption("I need help obtaining this");
    await mobile.getByRole("combobox", { name: "¿Puede presentar un comprobante del diagnóstico de cáncer?", exact: false }).selectOption("I need help obtaining this");
    await mobile.getByRole("button", { name: "Siguiente", exact: true }).click();
    await mobile.getByLabel("Nombre del paciente", { exact: false }).waitFor();
    await mobile.getByRole("combobox", { name: "Medio de contacto preferido", exact: false }).selectOption("Email");
    assert.equal(await mobile.locator('input[name="email"]').getAttribute("required"), "");
    assert.equal(await mobile.locator('input[name="phone"]').getAttribute("required"), null);
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const currentStep = mobile.getByRole("navigation", { name: "Pasos de la solicitud", exact: true }).locator('[aria-current="step"]');
    const box = await currentStep.boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= 390, `Current mobile step stays in view: ${JSON.stringify(box)}`);
    const inputBoxes = await mobile.locator('input[name="applicant_name"], input[name="email"], textarea[name="notes"]').evaluateAll((elements) => elements.map((element) => { const box = element.getBoundingClientRect(); return { x: box.x, right: box.right }; }));
    assert.ok(inputBoxes.every((box) => box.x >= 0 && box.right <= 390), "Mobile fields are not clipped");
    await mobile.screenshot({ path: "/tmp/nhcaf-apply-wizard-mobile.png", fullPage: true });
    assert.deepEqual(errors, []);
    console.log("PASS: seven-step wizard, English/Spanish, progress, validation, Back/Edit persistence, final consent, no early transmission, retry/idempotency, confirmation, cancel/reset, mobile and separate-window entry. Submission responses simulated; live Supabase not exercised.");
  } finally { await browser.close(); }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
